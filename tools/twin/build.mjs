/**
 * build.mjs · Draws the astronaut twin and writes src/js/twin/art.js.
 *
 *   node tools/twin/build.mjs              write the art module
 *   node tools/twin/build.mjs --audit      also prove the geometry (clearances, contacts, depth order)
 *   node tools/twin/build.mjs --preview f  also write a standalone HTML page to f, for screenshots
 *
 * The app itself has no build step: art.js is committed, and this script only runs when the
 * drawing changes. Dial marks come from src/js/config.js, so re-run it if the heart-rate limits change.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { k, A, P, R, WIDTH, HEIGHT, at, planeMatrix } from "./scene.mjs";
import { buildBase, buildStand, dialMarks, DIAL, CONSOLE_H } from "./stand.mjs";
import { buildSuit, DCM, DCM_SCREEN } from "./suit.mjs";
import { buildThoraxPort, heartOverlay } from "./overlays/heart.mjs";
import { CONFIG } from "../../src/js/config.js";

const HERE = dirname(fileURLToPath(import.meta.url));
const round = ([x, y]) => [+x.toFixed(1), +y.toFixed(1)];

const base = buildBase();
buildStand();
const suit = buildSuit();
const port = buildThoraxPort();

A.settle(R, P);
R.items.sort((a, b) => a.key - b.key);
const body = R.items.map((item) => item.svg).join("");

const heart = heartOverlay();
const marks = dialMarks(CONFIG.thresholds.hr);
const dcmFront = DCM.y + DCM.d;

const ART = {
  width: WIDTH,
  height: HEIGHT,
  label: "An astronaut in a pressure suit on a checkout stand. A view port on the left chest opens on the heart, and a dial on the console beside the boots reads heart rate.",
  base,
  body,
  /* Screen points the dashboard's link lines end on, one per metric. */
  anchors: Object.fromEntries(Object.entries({ ...suit.anchors, ...port.anchors }).map(([id, point]) => [id, round(at(point))])),
  dial: {
    plane: planeMatrix([...DIAL.centre, DIAL.z], [1, 0, 0], [0, 1, 0]),
    min: DIAL.min, max: DIAL.max, from: DIAL.from, span: DIAL.span, needle: DIAL.needle,
    normal: marks.normal,
    limits: marks.limits.map(round),
    thresholds: CONFIG.thresholds.hr,
  },
  screen: { plane: planeMatrix([DCM_SCREEN.x, dcmFront, DCM_SCREEN.z + DCM_SCREEN.h], [1, 0, 0], [0, 0, -1]), w: DCM_SCREEN.w, h: DCM_SCREEN.h },
  overlays: {
    hr: { cavity: heart.cavity, heart: heart.heart, plane: heart.plane, opening: heart.opening, bezel: heart.bezel, centre: round(heart.centre), port: round(heart.port), glow: Math.round(heart.glow) },
  },
};

const banner = `/* GENERATED by tools/twin/build.mjs — do not edit by hand.\n   Geometry lives in tools/twin/ (stand.mjs, suit.mjs, overlays/*.mjs). */\n`;
writeFileSync(join(HERE, "../../src/js/twin/art.js"), `${banner}export const ART = ${JSON.stringify(ART)};\n`);
console.log(`wrote src/js/twin/art.js · ${R.items.length} items · ${(JSON.stringify(ART).length / 1024).toFixed(0)} KB · scale ${P.scale.toFixed(2)}`);

const previewAt = process.argv.indexOf("--preview");
if (previewAt > 0) {
  const svg = k.figureSvg({ width: WIDTH, height: HEIGHT, label: ART.label, body: [base, body, process.argv.includes("--open") ? `<g>${heart.cavity}${heart.heart}</g>` : ""] });
  const extra = `<style>.twin-visor{fill:#2f5a55}.twin-glint{fill:none;stroke:#fff;stroke-width:1.2;stroke-linecap:round}.twin-screen{fill:#dfeeee}.twin-iris{fill:#fbfbfa}.twin-cavity{fill:#cfdcdc}.twin-lung{fill:#c6d6d6}.twin-cavity-back{fill:#bccfcf}
  .twin-mat-rubber{--anatomy-paper:#cfd9d6;--anatomy-face:#d6dfdc;--anatomy-top:#dde5e2;--anatomy-shade-0:#aebdb9;--anatomy-shade-1:#b9c7c3;--anatomy-shade-2:#c3d0cc;--anatomy-shade-3:#ccd7d4}</style>`;
  writeFileSync(process.argv[previewAt + 1], k.pageHtml({ title: "Twin preview", theme: "light", width: 700, body: extra + k.plateHtml({ fig: "Fig 1", title: "Suit checkout stand", hint: "", readout: "", keys: [], caption: "", body: `<div class="iso-stage">${svg}</div>` }) }));
  console.log("wrote preview", process.argv[previewAt + 1]);
}

A.auditOrExit(R, P);
